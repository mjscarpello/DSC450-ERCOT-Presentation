/* End-to-end verification for Milestone 3 scene authoring and review.
 * Run with the repo root at http://127.0.0.1:8765 and Playwright chromium installed. */
"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {chromium}=require("playwright");
const BASE="http://127.0.0.1:8765/ERCOT%20project%20context%20web/explorer.html";
const SHOTS="/tmp/ercot-explorer-screenshots";
(async()=>{
const browser=await chromium.launch({headless:true});const errors=[];
try{
 const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
 const page=await context.newPage();page.on("pageerror",e=>errors.push(e.message));
 await page.goto(BASE+"#workspace",{waitUntil:"networkidle"});
 await page.getByRole("heading",{name:"Assemble an evidence-backed explanation"}).waitFor();
 await page.getByRole("button",{name:"Add connected evidence"}).click();
 assert.ok(await page.locator(".ws-packet-item").count()>=3);
 await page.getByRole("button",{name:"Create presentation scene"}).click();
 await page.getByRole("heading",{name:"Design an evidence-backed presentation"}).waitFor();
 assert.equal(await page.locator(".scene-list-item").count(),1);
 let refs=await page.locator(".scene-selected").allInnerTexts();
 assert.ok(refs.some(t=>t.includes("Peak-hour model ranking reverses")),"missing finding");
 assert.ok(refs.some(t=>t.includes("F17")),"missing notebook figure");
 assert.ok(refs.some(t=>t.includes("Retrospective")||t.includes("Top")||t.includes("peak")),"expected a peak limitation");
 console.log("PASS: scene creation from evidence packet retains authoritative selected records");
 await page.getByRole("button",{name:"Record editorial approval"}).click();
 await page.locator("#scene-issues").waitFor();
 assert.match(await page.locator("#scene-issues").innerText(),/Narration is missing/);
 assert.match(await page.locator("#scene-issues").innerText(),/Reviewer name required/);
 console.log("PASS: cannot approve missing narration or reviewer");
 await page.getByLabel("Scene title").fill("Peak-demand performance");
 await page.getByLabel("Learning objective").fill("Understand how retrospective high-demand evaluation changes the ranking of our forecasting models.");
 await page.getByLabel("Speaker (optional)").fill("Data Visualizer");
 await page.getByLabel("Narration draft").fill("Among the highest 1% of actual-demand hours, rolling SARIMA outperformed the team's overall hybrid. These 88 hours were identified retrospectively, not known ahead of forecast time.");
 await page.getByLabel("On-screen statement").fill("Peak-hour accuracy changes model rankings.");
 await page.getByLabel("Reviewer name").fill("Team Reviewer");
 await page.getByLabel("I checked the original source files and their relevant locations.").check();
 await page.getByLabel("I checked the reported numbers, comparison sample and forecast conditions.").check();
 await page.getByLabel("I reviewed limitations, including retrospective peak categories and possible forecast-origin differences.").check();
 await page.getByRole("button",{name:"Record editorial approval"}).click();
 await page.locator(".scene-review-banner.approved").waitFor();
 assert.equal(await page.getByLabel("Narration draft").isDisabled(),true);
 console.log("PASS: named human sign-off, review checklist and approved-scene read-only lock");
 await page.screenshot({path:SHOTS+"/04-scene-reviewed-desktop.png",fullPage:true});
 console.log("SCENE_DESKTOP_PREVIEW="+(await page.screenshot({type:"jpeg",quality:25,fullPage:false})).toString("base64"));
 const rev=await page.evaluate(()=>{const s=sceneCurrent();return {status:sceneStatus(s),stamp:s.review.contentStamp,approvedAt:s.review.reviewedAt,signature:sceneStamp(s)};});
 assert.equal(rev.status,"approved");assert.equal(rev.stamp,rev.signature);
 await page.reload({waitUntil:"networkidle"});
 await page.locator(".scene-review-banner.approved").waitFor();
 console.log("PASS: approved scene persists and fingerprint matches current graph");
 await page.evaluate(()=>{state.byId.get("FIG-F17").summary+=" TEST altered data";render();});
 assert.equal(await page.locator(".scene-review-banner.stale").count(),1);
 console.log("PASS: approval is flagged stale after underlying source record changes");
 await page.reload({waitUntil:"networkidle"});
 await page.locator(".scene-review-banner.approved").waitFor();
 await page.getByRole("button",{name:"Reopen scene for edits"}).click();
 await page.locator(".scene-review-banner.draft").waitFor();
 await page.getByLabel("Narration draft").fill("Revised narration for team review.");
 assert.equal(await page.getByLabel("I checked the original source files and their relevant locations.").isChecked(),false);
 console.log("PASS: reopening approval resets human source checks before any new approval");
 await page.getByRole("button",{name:"Add blank scene"}).click();
 assert.equal(await page.locator(".scene-list-item").count(),2);
 await page.getByLabel("Move SCENE-002 earlier").click();
 const sequenceLabels=await page.locator(".scene-list-select").allInnerTexts();
 assert.ok(sequenceLabels[0].includes("Untitled"),"reordered scene should be first");
 const [download]=await Promise.all([
  page.waitForEvent("download"),
  page.getByRole("button",{name:"Export JSON"}).click()
 ]).catch(async e=>{throw e});
 const data=JSON.parse(fs.readFileSync(await download.path(),"utf8"));
 assert.equal(data.schema,"ercot-scene-sequence/v1");
 assert.equal(data.status,"draft-human-review");
 assert.equal(data.scenes.length,2);
 assert.equal(data.scenes[0].scene_id,"SCENE-002");
 assert.equal(data.scenes[1].scene_id,"SCENE-001");
 assert.ok(data.scenes[1].selected_ids.figures.includes("FIG-F17"));
 assert.ok(data.scenes[1].selected_ids.limitations.includes("LIMIT-PEAK-BIN"));
 assert.ok(data.scenes[1].authored_relationships.some(e=>e.from==="FIG-F17"&&e.to==="FIND-PEAK"));
 assert.match(data.studio_s_compatibility,/NOT a native Studio S/);
 assert.equal(data.scenes[1].review.status,"draft");
 console.log("PASS: ordered scene export preserves narrative, node IDs, links, caveats and non-native warning");
 const [notes]=await Promise.all([page.waitForEvent("download"),page.getByRole("button",{name:"Review notes"}).click()]);
 assert.match(fs.readFileSync(await notes.path(),"utf8"),/Scientific qualifications/);
 console.log("PASS: human-readable presentation review notes");
 page.once("dialog",d=>d.accept());
 await page.getByLabel("Import scene sequence JSON").setInputFiles({name:"scenes.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(data))});
 assert.equal(await page.locator(".scene-list-item").count(),2);
 assert.equal(await page.locator(".scene-review-banner.draft").count(),1);
 console.log("PASS: imported scene sequences remain drafts pending human review");
 const bad=structuredClone(data);bad.scenes[1].selected_ids.figures=["UNKNOWN-FIGURE"];
 await page.getByLabel("Import scene sequence JSON").setInputFiles({name:"invalid.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(bad))});
 assert.equal(await page.locator(".scene-list-item").count(),2);
 console.log("PASS: unknown figure reference rejected without overwriting local scenes");
 const mobile=await browser.newPage({viewport:{width:390,height:844}});
 mobile.on("pageerror",e=>errors.push(e.message));
 await mobile.goto(BASE+"#scenes",{waitUntil:"networkidle"});
 await mobile.getByRole("heading",{name:"Design an evidence-backed presentation"}).waitFor();
 await mobile.getByRole("button",{name:"Start a blank scene"}).click();
 const sizing=await mobile.evaluate(()=>({page:document.documentElement.scrollWidth,view:innerWidth}));
 assert.ok(sizing.page<=sizing.view+2,"mobile horizontal overflow: "+JSON.stringify(sizing));
 await mobile.screenshot({path:SHOTS+"/05-scene-mobile.png",fullPage:true});
 console.log("SCENE_MOBILE_PREVIEW="+(await mobile.screenshot({type:"jpeg",quality:25,fullPage:false})).toString("base64"));
 console.log("PASS: 390px mobile scene editor, no horizontal overflow");
 assert.deepEqual(errors,[]);
 console.log("PASS: no browser exceptions");
}finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
