/* End-to-end connection reference viewer checks: no presentation authoring. */
"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {chromium}=require("playwright");
const BASE="http://127.0.0.1:8765/ERCOT%20project%20context%20web/explorer.html";
const shots="/tmp/ercot-explorer-screenshots";
(async()=>{
 fs.mkdirSync(shots,{recursive:true});
 const browser=await chromium.launch({headless:true}),errors=[];
 try{
  const page=await browser.newPage({viewport:{width:1440,height:970}});
  page.on("pageerror",e=>errors.push(e.message));
  await page.goto(BASE,{waitUntil:"networkidle"});
  await page.getByRole("heading",{name:"Explore how the research fits together"}).waitFor();
  assert.match(page.url(),/explorer\.html$/);
  assert.equal(await page.locator('.nav-item[data-view="workspace"]').count(),0);
  assert.equal(await page.locator('.nav-item[data-view="scenes"]').count(),0);
  assert.equal(await page.locator('script[src*="scene-review"]').count(),0);
  assert.equal(await page.locator('script[src*="research-workspace"]').count(),0);
  assert.ok(await page.locator(".cx-node").count()>=4);
  assert.ok(await page.locator(".cx-curves path.cx-curve").count()>=4);
  console.log("PASS: connection-first landing; interactive SVG edges; no authoring modules");
  await page.screenshot({path:shots+"/04-connection-map-desktop.png",fullPage:true});
  console.log("CONN_PREVIEW_DESKTOP="+(await page.screenshot({type:"jpeg",quality:27,fullPage:false})).toString("base64"));
  await page.getByRole("combobox",{name:"Research focus concept"}).selectOption("FIND-PEAK");
  await page.getByRole("heading",{name:"Peak-hour model ranking reverses"}).waitFor();
  assert.match(page.url(),/#graph=FIND-PEAK/);
  const allCount=await page.locator(".cx-node").count();
  assert.ok(allCount>=6);
  const paths=await page.locator(".cx-curves path.cx-curve").count();
  assert.equal(paths,allCount);
  console.log("PASS: deep-linked research concept focus with curves connected to visible nodes");
  const limits=page.getByRole("button",{name:/Caveats ·/});
  await limits.click();
  assert.ok(await page.locator(".cx-node").count()>=1);
  assert.match(await page.locator(".cx-nodes").innerText(),/Top-demand groups only known after the fact/);
  await page.locator(".cx-node").first().getByRole("button",{name:"Why linked?"}).click();
  assert.match(await page.locator("#cx-explanation").innerText(),/qualifies/);
  assert.match(await page.locator("#cx-explanation").innerText(),/editorial strength/);
  assert.match(await page.locator("#cx-explanation").innerText(),/FIND-PEAK/);
  console.log("PASS: caveat filtering and authored relation rationale with direction");
  await page.locator(".cx-node").first().getByRole("button",{name:/Follow/}).click();
  assert.match(page.url(),/#graph=LIMIT-PEAK-BIN/);
  await page.getByRole("button",{name:/Back/}).click();
  assert.match(page.url(),/#graph=FIND-PEAK/);
  console.log("PASS: follow and return with central concept and browser URL preserved");
  await page.getByRole("button",{name:/All connections/}).click();
  await page.getByRole("button",{name:"Show more connections",exact:false}).click();
  assert.ok(await page.locator(".cx-node").count()>allCount);
  console.log("PASS: show more connections without truncating the graph index");
  await page.getByRole("button",{name:"Trace a path"}).click();
  await page.getByRole("combobox",{name:"Trace path target concept"}).selectOption("SRC-PRED");
  const route=page.locator(".cx-path-step");
  assert.ok(await route.count()>=2,"expected a research route to prediction CSV");
  assert.match(await page.locator(".cx-path-connection").first().innerText(),/relationship|result|support|link|computed|data/i);
  assert.match(await page.locator(".cx-method-note").innerText(),/not establish/);
  console.log("PASS: inspect multi-hop research explanation path and noncausal caveat");
  const fresh=await browser.newPage({viewport:{width:1060,height:900}});
  fresh.on("pageerror",e=>errors.push(e.message));
  await fresh.goto(BASE+"#graph=FIG-F17",{waitUntil:"networkidle"});
  await fresh.getByRole("heading",{name:/F17.*Forecast error/}).first().waitFor();
  assert.equal(await fresh.locator("#cx-hub").count(),1);
  await fresh.close();
  console.log("PASS: shareable graph deep links load with selected figure");
  const mobile=await browser.newPage({viewport:{width:390,height:844}});
  mobile.on("pageerror",e=>errors.push(e.message));
  await mobile.goto(BASE+"#graph=FIND-PEAK",{waitUntil:"networkidle"});
  await mobile.getByRole("heading",{name:"Explore how the research fits together"}).waitFor();
  await mobile.screenshot({path:shots+"/05-connection-map-mobile.png",fullPage:true});
  console.log("CONN_PREVIEW_MOBILE="+(await mobile.screenshot({type:"jpeg",quality:27,fullPage:false})).toString("base64"));
  const widths=await mobile.evaluate(()=>({document:document.documentElement.scrollWidth,window:innerWidth}));
  assert.ok(widths.document<=widths.window+2,JSON.stringify(widths));
  assert.ok(await mobile.locator(".cx-node").count()>=4);
  await mobile.getByRole("button",{name:"Trace a path"}).click();
  assert.ok(await mobile.locator(".cx-path-step").count()>=2);
  assert.deepEqual(errors,[]);
  console.log("PASS: 390px mobile map and path mode without overflow or browser errors");
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
