const assert=require("node:assert/strict");
const fs=require("node:fs");
const {chromium}=require("playwright");
const BASE="http://127.0.0.1:8765/ERCOT%20project%20context%20web/explorer.html";
const shots="/tmp/ercot-explorer-screenshots";
(async()=>{
 const browser=await chromium.launch({headless:true}),errors=[];
 fs.mkdirSync(shots,{recursive:true});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on("pageerror",e=>errors.push(e.message));
  await page.goto(BASE,{waitUntil:"networkidle"});
  await page.getByRole("heading",{name:"Understand the models. Follow the evidence."}).waitFor();
  assert.match(await page.locator("#page-content").innerText(),/8,640/);
  assert.match(await page.locator("#page-content").innerText(),/2,006/);
  await page.screenshot({path:shots+"/01-dashboard.png",fullPage:true});
  console.log("ERCOT_PREVIEW_DESKTOP="+(await page.screenshot({type:"jpeg",quality:25,fullPage:false})).toString("base64"));
  console.log("PASS: overview and summary metrics");
  await page.getByRole("link",{name:"Model comparison"}).click();
  await page.getByRole("button",{name:"Highest 1% demand"}).click();
  assert.match(await page.locator("#page-content").innerText(),/3,188.6/);
  assert.match(await page.locator("#page-content").innerText(),/AFTER observing demand/);
  console.log("PASS: model comparisons and high-demand caveat");
  await page.getByRole("link",{name:/Figure library/}).click();
  assert.equal(await page.locator(".figure-card").count(),38);
  const first=page.locator(".figure-card img").first();
  await first.evaluate(img=>img.decode());
  assert.equal(await first.evaluate(img=>img.naturalWidth>0),true);
  await page.screenshot({path:shots+"/02-figures.png",fullPage:true});
  await page.getByRole("textbox",{name:"Filter notebook figures"}).fill("F17");
  assert.equal(await page.locator(".figure-card").count(),1);
  await page.locator(".figure-card").click();
  await page.getByRole("dialog",{name:/F17/}).waitFor();
  await page.getByRole("button",{name:"Close details"}).click();
  console.log("PASS: 38 figures, valid image paths, filtering and detail dialog");
  await page.getByRole("button",{name:"Search all research"}).click();
  await page.getByRole("searchbox",{name:"Search research concepts"}).fill("SARIMA");
  assert.ok(await page.locator(".search-result").count()>0);
  await page.locator(".search-result").first().click();
  await page.locator(".detail-drawer").waitFor();
  await page.keyboard.press("Escape");
  await page.getByRole("link",{name:"Evidence connections"}).click();
  assert.ok(await page.locator(".graph-neighbor").count()>0);
  await page.locator(".graph-hub").click();
  await page.locator(".detail-drawer").waitFor();
  console.log("PASS: search, dialog and evidence navigation");
  await page.goto(BASE+"#node=FIND-PEAK",{waitUntil:"networkidle"});
  await page.getByRole("dialog",{name:/Peak-hour model ranking reverses/}).waitFor();
  await page.getByRole("button",{name:"Close details"}).click();
  await page.getByRole("heading",{name:"Understand the models. Follow the evidence."}).waitFor();
  console.log("PASS: direct node links and underlying overview restoration");
  const mobile=await browser.newPage({viewport:{width:390,height:844}});
  mobile.on("pageerror",e=>errors.push(e.message));
  await mobile.goto(BASE,{waitUntil:"networkidle"});
  await mobile.getByRole("heading",{name:"Understand the models. Follow the evidence."}).waitFor();
  await mobile.screenshot({path:shots+"/03-mobile.png",fullPage:true});
  console.log("ERCOT_PREVIEW_MOBILE="+(await mobile.screenshot({type:"jpeg",quality:25,fullPage:false})).toString("base64"));
  const size=await mobile.evaluate(()=>({scroll:document.documentElement.scrollWidth,view:innerWidth}));
  assert.ok(size.scroll<=size.view+2,"horizontal page overflow: "+JSON.stringify(size));
  await mobile.getByRole("link",{name:/Figure library/}).click();
  assert.equal(await mobile.locator(".figure-card").count(),38);
  assert.deepEqual(errors,[]);
  console.log("PASS: mobile 390px, all figure cards, no uncaught exceptions");
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
